// geminiGeneratedCallIDPrefix marks tool-call IDs minted locally because Gemini
// omitted the id on a function_call step. The Interactions API requires that id,
// so the minted one is echoed like any other to keep the call and its result paired.
const geminiGeneratedCallIDPrefix = "gemini_call_"

// geminiDummySignature is Google's documented placeholder thought signature for
// function_call steps that were not generated by a Gemini 3 model (for example
// history carried over from another provider).
const geminiDummySignature = "skip_thought_signature_validator"

// geminiRequest is the body of POST /v1beta/interactions. hmj is stateless: every
// request carries the full history in Input, and Store is always false so Google
// keeps nothing server-side. previous_interaction_id is never sent for that reason.
type geminiRequest struct {
	Model             string                  `json:"model"`
	SystemInstruction string                  `json:"system_instruction,omitempty"`
	Input             []geminiStep            `json:"input"`
	Tools             []geminiTool            `json:"tools,omitempty"`
	GenerationConfig  *geminiGenerationConfig `json:"generation_config,omitempty"`
	Store             bool                    `json:"store"`
	Stream            bool                    `json:"stream"`
}

// geminiGenerationConfig carries output-length and thinking settings.
type geminiGenerationConfig struct {
	MaxOutputTokens   int    `json:"max_output_tokens,omitzero"`
	ThinkingLevel     string `json:"thinking_level,omitempty"`
	ThinkingSummaries string `json:"thinking_summaries,omitempty"`
}

// geminiThinkingLevel maps a configured effort onto the Interactions thinking
// levels (minimal, low, medium, high). low and medium keep their level, and
// high, xhigh and max all use high. It returns "" when no effort is configured,
// which leaves the model's default level in place.
func geminiThinkingLevel(effort string) string {
	switch effort {
	case "":
		return ""
	case "low", "medium":
		return effort
	default:
		return "high"
	}
}

// geminiText is one text content part, used for user input, model output, thought
// summaries and function results.
type geminiText struct {
	Type string `json:"type"`
	Text string `json:"text"`
}

// geminiStep is one entry of the Interactions input list. Only the fields that
// belong to its Type are set; the rest are omitted from the JSON.
type geminiStep struct {
	Type      string         `json:"type"`
	Content   []geminiText   `json:"content,omitempty"`   // user_input, model_output
	Summary   []geminiText   `json:"summary,omitempty"`   // thought
	Signature string         `json:"signature,omitempty"` // thought, function_call
	ID        string         `json:"id,omitempty"`        // function_call
	Name      string         `json:"name,omitempty"`      // function_call, function_result
	Arguments map[string]any `json:"arguments,omitzero"`  // function_call
	CallID    string         `json:"call_id,omitempty"`   // function_result
	Result    []geminiText   `json:"result,omitempty"`    // function_result
}

// geminiTool declares a custom function. Parameters is a JSON Schema object.
type geminiTool struct {
	Type        string         `json:"type"`
	Name        string         `json:"name"`
	Description string         `json:"description,omitempty"`
	Parameters  map[string]any `json:"parameters"`
}

// convertMessagesToGemini maps the neutral message history onto Interactions
// input steps. System messages are returned joined for system_instruction. Thought
// blocks and function-call signatures are replayed exactly as the model produced
// them, because Gemini requires them to continue reasoning across turns.
func convertMessagesToGemini(messages []Message) (system string, input []geminiStep) {
	// A function_result step carries the function name, but a tool message only
	// has the call ID, so remember names as calls are seen.
	names := make(map[string]string)
	for _, msg := range messages {
		switch msg.Role {
		case "system":
			if system != "" {
				system += "\n\n"
			}
			system += msg.Content
		case "user":
			if msg.Content != "" {
				input = append(input, geminiStep{
					Type:    "user_input",
					Content: []geminiText{{Type: "text", Text: msg.Content}},
				})
			}
		case "tool":
			name := names[msg.ToolCallID]
			if name == "" {
				// The issuing call was compacted away; Gemini rejects an empty name.
				name = "unknown_tool"
			}
			input = append(input, geminiStep{
				Type:   "function_result",
				CallID: msg.ToolCallID,
				Name:   name,
				Result: []geminiText{{Type: "text", Text: msg.Content}},
			})
		case "assistant":
			// Thought steps come first, in the order the model produced them.
			for _, b := range msg.Blocks {
				if b.Type != "thought" {
					continue
				}
				step := geminiStep{Type: "thought", Signature: b.Signature}
				if b.Text != "" {
					step.Summary = []geminiText{{Type: "text", Text: b.Text}}
				}
				input = append(input, step)
			}
			if msg.Content != "" {
				input = append(input, geminiStep{
					Type:    "model_output",
					Content: []geminiText{{Type: "text", Text: msg.Content}},
				})
			}
			signed := slices.ContainsFunc(msg.ToolCalls, func(tc ToolCall) bool {
				return tc.ThoughtSignature != ""
			})
			for i, tc := range msg.ToolCalls {
				names[tc.ID] = tc.Function.Name
				step := geminiStep{
					Type:      "function_call",
					ID:        tc.ID,
					Name:      tc.Function.Name,
					Arguments: geminiToolArgs(tc.Function.Arguments),
					Signature: tc.ThoughtSignature,
				}
				if i == 0 && !signed {
					step.Signature = geminiDummySignature
				}
				input = append(input, step)
			}
		}
	}
	return system, input
}

// geminiToolArgs decodes a tool-call arguments string into the object Gemini
// expects for function_call.arguments. It reuses the Anthropic conversion, which
// keeps unparseable arguments under a well-known key instead of dropping them. The
// result is never nil, so the field is always sent.
func geminiToolArgs(arguments string) map[string]any {
	return anthropicToolInput(arguments)
}

func convertToolsToGemini(tools []ToolDefinition) []geminiTool {
	if len(tools) == 0 {
		return nil
	}
	decls := make([]geminiTool, 0, len(tools))
	for _, t := range tools {
		schema := t.Function.Parameters
		if schema == nil {
			schema = map[string]any{"type": "object", "properties": map[string]any{}}
		}
		decls = append(decls, geminiTool{
			Type:        "function",
			Name:        t.Function.Name,
			Description: t.Function.Description,
			Parameters:  schema,
		})
	}
	return decls
}

// geminiModelName strips an optional "models/" prefix from a model ID. The
// Interactions "model" field takes the bare ID.
func geminiModelName(modelID string) string {
	return strings.TrimPrefix(modelID, "models/")
}

// geminiInteractionsURL builds the Interactions endpoint from a Gemini base URL,
// which is {host}/v1beta/interactions. A base URL ending in /v1beta (the form
// hmj configs use) gets /interactions appended. A bare host, or one ending in /v1,
// gets /v1beta/interactions. A URL already ending in /interactions is used as is.
// Users therefore never need to change their config for the new API.
func geminiInteractionsURL(baseURL string) string {
	base := strings.TrimRight(baseURL, "/")
	if strings.HasSuffix(base, "/interactions") {
		return base
	}
	base = strings.TrimSuffix(base, "/v1beta")
	base = strings.TrimSuffix(base, "/v1")
	return base + "/v1beta/interactions"
}

// geminiStreamEvent is one server-sent event of a streamed interaction. Each event
// carries its event_type, and only the fields for that type are set.
type geminiStreamEvent struct {
	EventType   string             `json:"event_type"`
	Index       int                `json:"index"`
	Step        *geminiStreamStep  `json:"step"`
	Delta       *geminiStreamDelta `json:"delta"`
	Interaction *geminiInteraction `json:"interaction"`
	Error       *geminiError       `json:"error"`
}

// geminiStreamStep is the step announced by step.start. A function_call step
// carries its id, name and signature here, and its arguments arrive as deltas.
type geminiStreamStep struct {
	Type      string         `json:"type"`
	ID        string         `json:"id"`
	Name      string         `json:"name"`
	Arguments map[string]any `json:"arguments"`
	Signature string         `json:"signature"`
}

// geminiStreamDelta is one step.delta. Its type decides which field is set: text,
// thought_summary (Content), thought_signature (Signature) or arguments_delta
// (Arguments, a partial JSON string).
type geminiStreamDelta struct {
	Type      string      `json:"type"`
	Text      string      `json:"text"`
	Content   *geminiText `json:"content"`
	Signature string      `json:"signature"`
	Arguments string      `json:"arguments"`
}

// geminiInteraction is the interaction object carried by interaction.completed.
type geminiInteraction struct {
	Status string        `json:"status"`
	Usage  *geminiUsage  `json:"usage"`
	Errors []geminiError `json:"errors"`
}

// geminiUsage holds the token totals of an interaction. Thought tokens are
// reported apart from output tokens.
type geminiUsage struct {
	TotalInputTokens   int `json:"total_input_tokens"`
	TotalOutputTokens  int `json:"total_output_tokens"`
	TotalThoughtTokens int `json:"total_thought_tokens"`
	TotalCachedTokens  int `json:"total_cached_tokens"`
	TotalTokens        int `json:"total_tokens"`
}

// geminiError is an error object, either in a stream error event or in an HTTP
// error body. Code is a string such as "not_found" in the Interactions API.
type geminiError struct {
	Code    string `json:"code"`
	Message string `json:"message"`
}

// geminiStepState collects one streamed step until the accumulator builds the
// final message from it.
type geminiStepState struct {
	kind      string
	summary   strings.Builder
	signature string
	id        string
	name      string
	args      strings.Builder
	startArgs map[string]any
}

type geminiAccumulator struct {
	startTime      time.Time
	firstToken     time.Time
	contentBuilder strings.Builder
	steps          map[int]*geminiStepState
	// callNonce keeps minted call IDs distinct across turns of one conversation.
	callNonce string
	status    string
	usage     *geminiUsage
}

func newGeminiAccumulator(startTime time.Time) *geminiAccumulator {
	return &geminiAccumulator{
		startTime: startTime,
		steps:     make(map[int]*geminiStepState),
		callNonce: strconv.FormatUint(rand.Uint64(), 36),
	}
}

// stepState returns the state for the step at index, creating it on first use.
func (a *geminiAccumulator) stepState(index int) *geminiStepState {
	st := a.steps[index]
	if st == nil {
		st = &geminiStepState{}
		a.steps[index] = st
	}
	return st
}

// handle processes one SSE event. eventType is the SSE event: name, which is used
// only when the data carries no event_type.
func (a *geminiAccumulator) handle(eventType, data string, onReasoning, onDelta func(string)) error {
	trimmed := strings.TrimSpace(data)
	if trimmed == "" || trimmed == "[DONE]" {
		return nil
	}

	var ev geminiStreamEvent
	if err := json.Unmarshal([]byte(trimmed), &ev); err != nil {
		return fmt.Errorf("gemini stream: invalid event JSON: %w (snippet: %s)", err, truncateErrorBody([]byte(trimmed), 200))
	}
	if ev.Error != nil {
		return fmt.Errorf("gemini stream error: %s", redact.String(ev.Error.Message))
	}
	if ev.EventType == "" {
		ev.EventType = eventType
	}

	switch ev.EventType {
	case "interaction.completed":
		if ev.Interaction == nil {
			return nil
		}
		// Usage and the final status arrive only here. Usage is cumulative, so the last one wins.
		a.status = ev.Interaction.Status
		if ev.Interaction.Usage != nil {
			a.usage = ev.Interaction.Usage
		}
		if ev.Interaction.Status == "failed" {
			msg := "interaction failed"
			if len(ev.Interaction.Errors) > 0 {
				msg = ev.Interaction.Errors[0].Message
			}
			return fmt.Errorf("gemini stream error: %s", redact.String(msg))
		}
	case "step.start":
		if ev.Step == nil {
			return nil
		}
		st := a.stepState(ev.Index)
		st.kind = ev.Step.Type
		st.id = ev.Step.ID
		st.name = ev.Step.Name
		st.signature = ev.Step.Signature
		st.startArgs = ev.Step.Arguments
		if st.kind == "function_call" {
			a.markFirstToken()
		}
	case "step.delta":
		if ev.Delta == nil {
			return nil
		}
		st := a.stepState(ev.Index)
		switch ev.Delta.Type {
		case "text":
			a.markFirstToken()
			a.contentBuilder.WriteString(ev.Delta.Text)
			if onDelta != nil {
				onDelta(ev.Delta.Text)
			}
		case "thought_summary":
			if ev.Delta.Content == nil || ev.Delta.Content.Text == "" {
				return nil
			}
			a.markFirstToken()
			st.summary.WriteString(ev.Delta.Content.Text)
			if onReasoning != nil {
				onReasoning(ev.Delta.Content.Text)
			}
		case "thought_signature":
			st.signature = ev.Delta.Signature
		case "arguments_delta":
			st.args.WriteString(ev.Delta.Arguments)
		}
	}
	return nil
}

func (a *geminiAccumulator) markFirstToken() {
	if a.firstToken.IsZero() {
		a.firstToken = time.Now()
	}
}

// geminiFinishReason maps an Interactions status onto the values the rest of the
// app uses: incomplete (the output limit was reached) becomes "length", which the
// agent flags as truncation, completed becomes "stop", requires_action (a function
// call awaits its result) becomes "tool_calls", and anything else is lowercased.
func geminiFinishReason(status string) string {
	switch status {
	case "incomplete":
		return "length"
	case "completed":
		return "stop"
	case "requires_action":
		return "tool_calls"
	default:
		return strings.ToLower(status)
	}
}

func (a *geminiAccumulator) result() (Message, *TokenUsage) {
	totalDuration := time.Since(a.startTime)
	var ttft time.Duration
	if !a.firstToken.IsZero() {
		ttft = a.firstToken.Sub(a.startTime)
	}

	// Steps are read in index order, which is the order the model produced them.
	var (
		toolCalls []ToolCall
		blocks    []Block
	)
	for _, index := range slices.Sorted(maps.Keys(a.steps)) {
		st := a.steps[index]
		switch st.kind {
		case "thought":
			blocks = append(blocks, Block{Type: "thought", Text: st.summary.String(), Signature: st.signature})
		case "function_call":
			id := st.id
			if id == "" {
				id = fmt.Sprintf("%s%s_%d", geminiGeneratedCallIDPrefix, a.callNonce, len(toolCalls)+1)
			}
			args := st.args.String()
			if args == "" {
				args = "{}"
				if st.startArgs != nil {
					if raw, err := json.Marshal(st.startArgs); err == nil {
						args = string(raw)
					}
				}
			}
			toolCalls = append(toolCalls, ToolCall{
				ID:               id,
				Type:             "function",
				Function:         ToolCallFunction{Name: st.name, Arguments: args},
				ThoughtSignature: st.signature,
			})
		}
	}

	usage := &TokenUsage{}
	if m := a.usage; m != nil {
		// Thought tokens are billed as output, so they count as completion tokens.
		completion := m.TotalOutputTokens + m.TotalThoughtTokens
		usage = &TokenUsage{
			PromptTokens:     m.TotalInputTokens,
			CompletionTokens: completion,
			TotalTokens:      m.TotalTokens,
			InputTokens:      m.TotalInputTokens,
			OutputTokens:     completion,
			CachedTokens:     m.TotalCachedTokens,
		}
	}
	if usage.TotalTokens == 0 {
		usage.TotalTokens = usage.PromptTokens + usage.CompletionTokens
	}
	usage.Duration = totalDuration
	usage.TTFT = ttft
	usage.FinishReason = geminiFinishReason(a.status)
	if usage.CompletionTokens > 0 && !a.firstToken.IsZero() {
		genSec := time.Since(a.firstToken).Seconds()
		if genSec > 0 {
			usage.TokensPerSecond = float64(usage.CompletionTokens) / genSec
		}
	}

	return Message{
		Role:      "assistant",
		Content:   a.contentBuilder.String(),
		ToolCalls: toolCalls,
		Blocks:    blocks,
	}, usage
}

// streamGeminiOnce executes one streaming request against the Interactions API
// (POST {baseURL}/v1beta/interactions with "stream": true, see geminiInteractionsURL).
func (c *Client) streamGeminiOnce(
	ctx context.Context,
	provider config.Provider,
	model config.Model,
	messages []Message,
	tools []ToolDefinition,
	onReasoning func(string),
	onDelta func(string),
) (Message, *TokenUsage, time.Duration, bool, error) {
	systemPrompt, input := convertMessagesToGemini(messages)
	reqPayload := geminiRequest{
		Model:             geminiModelName(model.ID),
		SystemInstruction: systemPrompt,
		Input:             input,
		Tools:             convertToolsToGemini(tools),
		Store:             false,
		Stream:            true,
	}
	if model.ThinkingEnabled() || model.MaxOutputTokens > 0 {
		gc := &geminiGenerationConfig{MaxOutputTokens: model.MaxOutputTokens}
		if model.ThinkingEnabled() {
			// Thought summaries are requested so reasoning streams live, as it does for the other protocols.
			gc.ThinkingLevel = geminiThinkingLevel(model.Effort)
			gc.ThinkingSummaries = "auto"
		}
		reqPayload.GenerationConfig = gc
	}

	body, err := json.Marshal(reqPayload)
	if err != nil {
		return Message{}, nil, 0, false, err
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, geminiInteractionsURL(provider.BaseURL), bytes.NewReader(body))
	if err != nil {
		return Message{}, nil, 0, false, err
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "text/event-stream")
	if key := config.ResolveAPIKey(provider.APIKey); key != "" {
		req.Header.Set("x-goog-api-key", key)
	}

	startTime := time.Now()
	acc := newGeminiAccumulator(startTime)
	retryAfter, retryable, err := c.doStream(ctx, req, func(eventType, data string) error {
		return acc.handle(eventType, data, onReasoning, onDelta)
	}, func() bool { return !acc.firstToken.IsZero() })
	if err != nil {
		return Message{}, nil, retryAfter, retryable, err
	}

	msg, usage := acc.result()
	return msg, usage, 0, false, nil
}
